-- =====================================================================
-- DeservEat - Production star schema (PostgreSQL 15+ / PostGIS 3+)
-- Grain of fact_calorie_burn: ONE ROW PER DISH WHOSE CALORIES ARE TO BE BURNED,
--   for one user at one moment, with one restaurant, one activity,
--   one itinerary and 0..1 landmark.
-- Column names follow the processed CSV files (p_*.csv) so they can be loaded directly.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE SCHEMA IF NOT EXISTS landing;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;
SET search_path = dw, public;

-- ---------------------------------------------------------------------
-- dim_date  (Static) - generated here in SQL, one row per calendar day (2026-01-01 to 2027-12-31)
-- ---------------------------------------------------------------------
CREATE TABLE dim_date (
    date_key     INT      PRIMARY KEY,                -- YYYYMMDD, e.g. 20261020
    full_date    DATE     NOT NULL UNIQUE,
    day_of_week  INT      NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO: 1 = Monday
    day_name     TEXT     NOT NULL,
    month        INT      NOT NULL CHECK (month BETWEEN 1 AND 12),
    year         INT      NOT NULL,
    is_weekend   BOOLEAN  NOT NULL
);

INSERT INTO dim_date (date_key, full_date, day_of_week, day_name, month, year, is_weekend)
SELECT to_char(d, 'YYYYMMDD')::INT,
       d::DATE,
       EXTRACT(ISODOW FROM d)::INT,
       trim(to_char(d, 'Day')),
       EXTRACT(MONTH FROM d)::INT,
       EXTRACT(YEAR FROM d)::INT,
       EXTRACT(ISODOW FROM d) IN (6, 7)
FROM generate_series('2026-01-01'::DATE, '2027-12-31'::DATE, INTERVAL '1 day') AS d;

-- ---------------------------------------------------------------------
-- dim_activity  (Static) - p_met.csv (Compendium of Physical Activities)
-- 9 rows: 3 speeds (slow, moderate, fast) for each of walking, running and cycling.
-- activity_name is the label shown to the user; activity_key is the Compendium code of the row.
-- ---------------------------------------------------------------------
CREATE TABLE dim_activity (
    activity_key   INT           PRIMARY KEY,
    activity_name  TEXT          NOT NULL UNIQUE,            -- e.g. 'Moderate Walk'
    intensity      INT           NOT NULL CHECK (intensity BETWEEN 1 AND 3),  -- from the MET score: 1 light, 2 moderate, 3 vigorous
    met_value      NUMERIC(4,2)  NOT NULL CHECK (met_value > 0),
    speed_kmh      NUMERIC(5,2)  NOT NULL CHECK (speed_kmh > 0)
);

-- ---------------------------------------------------------------------
-- dim_recipe  (SCD Type 1) - HUMMUS recipes (p_recipes.csv)
-- ---------------------------------------------------------------------
CREATE TABLE dim_recipe (
    recipe_key        INT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id         INT   NOT NULL UNIQUE,                 -- recipe_id from the source
    title             TEXT  NOT NULL,
    total_kcal        INT   CHECK (total_kcal >= 0),         -- kcal_per_serving * servings (NULL if servings unknown)
    kcal_per_serving  INT   NOT NULL CHECK (kcal_per_serving BETWEEN 1 AND 3000),
    category          TEXT,                                  -- cuisine type, to match dim_restaurant.food_type
    ingredients       TEXT,
    recipe_url        TEXT,
    servings          INT   CHECK (servings > 0)
);

-- ---------------------------------------------------------------------
-- dim_restaurant  (SCD Type 1) - Kaggle "Lyon Restaurant Reviews" (p_restaurants.csv)
-- ---------------------------------------------------------------------
CREATE TABLE dim_restaurant (
    restaurant_key   INT               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        BIGINT            NOT NULL UNIQUE,      -- source has no ID: first 15 hex digits of md5(restaurant_name|lat|lng), read as a number
    restaurant_name  TEXT              NOT NULL,
    food_type        TEXT,
    lat              DOUBLE PRECISION  NOT NULL,
    lng              DOUBLE PRECISION  NOT NULL,
    geom             GEOGRAPHY(Point, 4326) NOT NULL,        -- ST_MakePoint(lng, lat)
    overall_rating   NUMERIC(3,2)      CHECK (overall_rating BETWEEN 0 AND 5),
    district         TEXT,
    -- DQ: same loose bounding box as processing_restaurants.py
    CONSTRAINT chk_restaurant_bbox CHECK (lat BETWEEN 45.4 AND 46.1
                                      AND lng BETWEEN 4.5 AND 5.3)
);

-- ---------------------------------------------------------------------
-- dim_landmark  (SCD Type 1) - Monuments Historiques (p_landmarks.csv)
-- landmark_key is generated by the database; source_id is the Merimee reference from the CSV.
-- There is no "No landmark" row: a fact without landmark has landmark_key NULL.
-- ---------------------------------------------------------------------
CREATE TABLE dim_landmark (
    landmark_key  INT               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     TEXT              NOT NULL UNIQUE,         -- Merimee reference (e.g. PA00117123)
    building_name TEXT              NOT NULL,
    address       TEXT,
    commune       TEXT,
    insee_code    CHAR(5),
    lat           DOUBLE PRECISION  NOT NULL,
    lon           DOUBLE PRECISION  NOT NULL,
    geom          GEOGRAPHY(Point, 4326) NOT NULL,
    -- DQ: same loose bounding box as processing_landmarks.py
    CONSTRAINT chk_landmark_coords CHECK (lat BETWEEN 45.4 AND 46.1
                                      AND lon BETWEEN 4.5 AND 5.3)
);

-- ---------------------------------------------------------------------
-- dim_user  (SCD Type 2) - synthetic users; new row when weight changes
-- ---------------------------------------------------------------------
CREATE TABLE dim_user (
    user_key    INT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     TEXT          NOT NULL,                      -- natural/business key
    weight_kg   NUMERIC(5,1)  NOT NULL CHECK (weight_kg BETWEEN 30 AND 250),
    valid_from  TIMESTAMPTZ   NOT NULL,
    valid_to    TIMESTAMPTZ   NOT NULL DEFAULT '9999-12-31 00:00:00+00',
    is_current  BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_user_validity CHECK (valid_to > valid_from)
);
-- DQ: at most one current version per user
CREATE UNIQUE INDEX ux_dim_user_current ON dim_user (user_id) WHERE is_current;

-- ---------------------------------------------------------------------
-- dim_itinerary  - start and end points of the generated route
-- ---------------------------------------------------------------------
CREATE TABLE dim_itinerary (
    itinerary_key  INT                     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_point    GEOGRAPHY(Point, 4326)  NOT NULL,         -- rounded to ~200 m
    end_point      GEOGRAPHY(Point, 4326)  NOT NULL
);

-- ---------------------------------------------------------------------
-- fact_calorie_burn - one row per dish whose calories are to be burned
-- ---------------------------------------------------------------------
CREATE TABLE fact_calorie_burn (
    calorie_burn_key  INT           GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    recipe_key        INT           NOT NULL REFERENCES dim_recipe (recipe_key),
    activity_key      INT           NOT NULL REFERENCES dim_activity (activity_key),
    landmark_key      INT           REFERENCES dim_landmark (landmark_key),   -- NULL = no landmark
    user_key          INT           NOT NULL REFERENCES dim_user (user_key),  -- version valid at requested_at
    restaurant_key    INT           NOT NULL REFERENCES dim_restaurant (restaurant_key),
    date_key          INT           NOT NULL REFERENCES dim_date (date_key),
    itinerary_key     INT           NOT NULL REFERENCES dim_itinerary (itinerary_key),
    kcal_to_burn      INT           NOT NULL CHECK (kcal_to_burn > 0),        -- 1 serving, snapshot
    distance_km       NUMERIC(7,2)  NOT NULL CHECK (distance_km >= 0),
    duration_min      NUMERIC(7,1)  NOT NULL CHECK (duration_min > 0),
    requested_at      TIMESTAMPTZ   NOT NULL,
    -- idempotence: the same request cannot be loaded twice
    CONSTRAINT uq_fact_request UNIQUE (user_key, recipe_key, restaurant_key, activity_key, requested_at)
);

CREATE INDEX ix_fact_recipe     ON fact_calorie_burn (recipe_key);
CREATE INDEX ix_fact_activity   ON fact_calorie_burn (activity_key);
CREATE INDEX ix_fact_landmark   ON fact_calorie_burn (landmark_key);
CREATE INDEX ix_fact_user       ON fact_calorie_burn (user_key);
CREATE INDEX ix_fact_restaurant ON fact_calorie_burn (restaurant_key);
CREATE INDEX ix_fact_date       ON fact_calorie_burn (date_key);
CREATE INDEX ix_fact_itinerary  ON fact_calorie_burn (itinerary_key);
CREATE INDEX ix_fact_requested  ON fact_calorie_burn (requested_at);