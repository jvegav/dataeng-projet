-- =====================================================================
-- DeservEat – Production star schema (PostgreSQL 15+ / PostGIS 3+)
-- Grain of fact_itinerary: ONE ROW PER ITINERARY GENERATED
--   (one user request = 1 recipe serving x 1 activity x 1 restaurant
--    x 0..1 landmark, at one point in time)
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE SCHEMA IF NOT EXISTS dw;
SET search_path = dw, public;

-- ---------------------------------------------------------------------
-- dim_date  (Static) – generated once by SQL, one row per calendar day
-- ---------------------------------------------------------------------
CREATE TABLE dim_date (
    date_key     INT      PRIMARY KEY,                -- YYYYMMDD, e.g. 20261020
    full_date    DATE     NOT NULL UNIQUE,
    day_of_week  INT      NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),  -- ISO: 1 = Monday
    day_name     TEXT     NOT NULL,
    month        INT      NOT NULL CHECK (month BETWEEN 1 AND 12),
    year         INT      NOT NULL,
    is_weekend   BOOLEAN  NOT NULL
);

-- ---------------------------------------------------------------------
-- dim_activity  (Static) – manual MET seed CSV (Compendium of Physical Activities)
-- ---------------------------------------------------------------------
CREATE TABLE dim_activity (
    activity_key   INT           PRIMARY KEY,
    activity_name  TEXT          NOT NULL UNIQUE
                                 CHECK (activity_name IN ('walking', 'running', 'cycling')),
    intensity      INT           NOT NULL CHECK (intensity BETWEEN 1 AND 3),  -- 1 low, 2 moderate, 3 vigorous
    met_value      NUMERIC(4,2)  NOT NULL CHECK (met_value > 0),
    speed_kmh      NUMERIC(5,2)  NOT NULL CHECK (speed_kmh > 0)
);

-- ---------------------------------------------------------------------
-- dim_recipe  (SCD Type 1) – Food.com / HUMMUS recipes (GitLab recipes.zip)
-- ---------------------------------------------------------------------
CREATE TABLE dim_recipe (
    recipe_key        INT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id         TEXT  NOT NULL UNIQUE,                 -- recipe_id from source
    recipe_name       TEXT  NOT NULL,
    total_kcal        INT   CHECK (total_kcal >= 0),         -- kcal_per_serving * servings
    kcal_per_serving  INT   NOT NULL CHECK (kcal_per_serving BETWEEN 1 AND 3000),
    category          TEXT  NOT NULL DEFAULT 'other'
                            CHECK (category IN ('main', 'dessert', 'breakfast',
                                                'appetizer_snack', 'side_salad', 'other')),
    ingredients       TEXT,                                  -- comma-separated ingredient names
    source_file       TEXT  NOT NULL,                        -- lineage, e.g. 'recipes.zip/pp_recipes.csv'
    servings          INT   CHECK (servings > 0)
);

-- ---------------------------------------------------------------------
-- dim_restaurant  (SCD Type 1) – Kaggle "Lyon Restaurant Reviews"
-- ---------------------------------------------------------------------
CREATE TABLE dim_restaurant (
    restaurant_key   INT               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id        TEXT              NOT NULL UNIQUE,      -- md5(restaurant_name|lat|lng): source has no ID
    name             TEXT              NOT NULL,
    cuisine          TEXT,                                   -- food_type
    lat              DOUBLE PRECISION  NOT NULL,
    lon              DOUBLE PRECISION  NOT NULL,
    geom             GEOGRAPHY(Point, 4326) NOT NULL,        -- ST_MakePoint(lon, lat)
    rating           NUMERIC(2,1)      CHECK (rating BETWEEN 0 AND 5),
    -- DQ: coordinates must fall inside a Lyon metropolitan bounding box
    CONSTRAINT chk_restaurant_bbox CHECK (lat BETWEEN 45.55 AND 45.95
                                      AND lon BETWEEN 4.65 AND 5.15)
);

-- ---------------------------------------------------------------------
-- dim_landmark  (SCD Type 1) – data.gouv.fr "Immeubles protégés au titre des MH"
-- Row landmark_key = -1 is the "No landmark" member (itinerary without landmark)
-- ---------------------------------------------------------------------
CREATE TABLE dim_landmark (
    landmark_key  INT               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     TEXT              NOT NULL UNIQUE,         -- Mérimée reference (e.g. PA00117xxx)
    name          TEXT              NOT NULL,
    address       TEXT,
    commune       TEXT,
    insee_code    CHAR(5),
    lat           DOUBLE PRECISION,
    lon           DOUBLE PRECISION,
    geom          GEOGRAPHY(Point, 4326),
    -- every real landmark must have valid Lyon coordinates; only -1 may lack them
    CONSTRAINT chk_landmark_coords CHECK (
        landmark_key = -1
        OR (geom IS NOT NULL
            AND lat BETWEEN 45.55 AND 45.95
            AND lon BETWEEN 4.65 AND 5.15))
);

-- ---------------------------------------------------------------------
-- dim_user  (SCD Type 2) – synthetic users; new row when weight changes
-- ---------------------------------------------------------------------
CREATE TABLE dim_user (
    user_key    INT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     TEXT          NOT NULL,                      -- natural/business key
    weight_kg   NUMERIC(5,1)  NOT NULL CHECK (weight_kg BETWEEN 30 AND 250),
    valid_from  TIMESTAMPTZ   NOT NULL,
    valid_to    TIMESTAMPTZ   NOT NULL DEFAULT '9999-12-31 00:00:00+00',
    is_current  BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_user_validity CHECK (valid_to > valid_from)
);
-- DQ: at most one current version per user
CREATE UNIQUE INDEX ux_dim_user_current ON dim_user (user_id) WHERE is_current;

-- ---------------------------------------------------------------------
-- fact_itinerary – one row per itinerary generated
-- ---------------------------------------------------------------------
CREATE TABLE fact_itinerary (
    itinerary_key   INT           GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    recipe_key      INT           NOT NULL REFERENCES dim_recipe (recipe_key),
    activity_key    INT           NOT NULL REFERENCES dim_activity (activity_key),
    landmark_key    INT           NOT NULL DEFAULT -1 REFERENCES dim_landmark (landmark_key),
    user_key        INT           NOT NULL REFERENCES dim_user (user_key),  -- version valid at requested_at
    restaurant_key  INT           NOT NULL REFERENCES dim_restaurant (restaurant_key),
    date_key        INT           NOT NULL REFERENCES dim_date (date_key),
    start_point     GEOGRAPHY(Point, 4326) NOT NULL,         -- restaurant location
    end_point       GEOGRAPHY(Point, 4326) NOT NULL,         -- landmark, or restaurant if no landmark (loop)
    kcal_to_burn    INT           NOT NULL CHECK (kcal_to_burn > 0),        -- 1 serving, snapshot
    distance_km     NUMERIC(7,2)  NOT NULL CHECK (distance_km >= 0),
    duration_min    NUMERIC(7,1)  NOT NULL CHECK (duration_min > 0),
    requested_at    TIMESTAMPTZ   NOT NULL
);

CREATE INDEX ix_fact_recipe     ON fact_itinerary (recipe_key);
CREATE INDEX ix_fact_activity   ON fact_itinerary (activity_key);
CREATE INDEX ix_fact_landmark   ON fact_itinerary (landmark_key);
CREATE INDEX ix_fact_user       ON fact_itinerary (user_key);
CREATE INDEX ix_fact_restaurant ON fact_itinerary (restaurant_key);
CREATE INDEX ix_fact_date       ON fact_itinerary (date_key);
